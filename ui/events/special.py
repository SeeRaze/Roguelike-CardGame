# Условие: у игрока есть флаг gm.has_basilisk_egg (внутр. идентификатор сохранён;
# флейвор — «утёкший прод-токен». Сеттер флага пока нигде нет → событие дремлет.)
def _has_basilisk_egg(gm):
    return getattr(gm, "has_basilisk_egg", False)


# Условие РАЗВЯЗКИ испытания «Марш смерти» (С72): флаг ставит ЗАВЯЗКА «Кранч»
# (neutral.py, set_flag:death_march). Пока флаг стоит, развязка крутится в пуле
# (вес ×2) — раскрывает скрытый пейофф и выдаёт легендарку. См. [[legendary-challenges]].
def _death_march_pledged(gm):
    return getattr(gm, "death_march", False)


# ── ИСПЫТАНИЕ «Точка отказа» (С72, раскатка Z2). ОРТОГОНАЛЬНО мете (Option A):
# завязка «Незаменимый» появляется, ТОЛЬКО если легендарка открыта в мете (казино)
# — так мета «открывает испытание», а рандом-дроп убран ([[legendary-challenges]]).
def _point_of_failure_offered(gm):
    """Условие ЗАВЯЗКИ «Незаменимый»: легендарка открыта в мете, не в инвентаре,
    испытание ещё не начато (флаг не стоит). Иначе крутится развязка / ничего."""
    from core.progression import is_relic_unlocked
    if getattr(gm, "point_of_failure", False):
        return False                       # уже подписан → крутится развязка
    if not is_relic_unlocked(getattr(gm, "meta", None), "ТочкаОтказа"):
        return False                       # мета ещё не открыла «в принципе»
    return all(type(r).__name__ != "ТочкаОтказа" for r in getattr(gm, "relics", []))


def _point_of_failure_pledged(gm):
    """Условие РАЗВЯЗКИ «Точка отказа»: завязка поставила флаг point_of_failure."""
    return getattr(gm, "point_of_failure", False)


# ── ИСПЫТАНИЕ «Деплой в пятницу» (С72, раскатка Z3). Мета-канал — ачивка «Первый
# деплой» (победить первого босса) пишет анлок в meta['unlocks']; завязка «Пятница,
# 17:00» появляется только при нём (Option A — мета открывает испытание). ──
def _friday_deploy_offered(gm):
    """Условие ЗАВЯЗКИ «Пятница, 17:00»: легендарка открыта в мете (ачивкой), не в
    инвентаре, испытание ещё не начато (флаг не стоит)."""
    from core.progression import is_relic_unlocked
    if getattr(gm, "friday_deploy", False):
        return False                       # уже подписан → крутится развязка
    if not is_relic_unlocked(getattr(gm, "meta", None), "ДеплойВПятницу"):
        return False                       # мета ещё не открыла «в принципе»
    return all(type(r).__name__ != "ДеплойВПятницу" for r in getattr(gm, "relics", []))


def _friday_deploy_pledged(gm):
    """Условие РАЗВЯЗКИ «Деплой в пятницу»: завязка поставила флаг friday_deploy."""
    return getattr(gm, "friday_deploy", False)


